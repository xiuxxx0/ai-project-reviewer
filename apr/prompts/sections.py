_BODIES = {1: _BODY_1, 2: _BODY_2, 3: _BODY_3}


def _system(language: str, task: str) -> str:
    lang = _LANG_HINT.get(language, _LANG_HINT["zh"])
    return (
        f"[TASK: {task}]\n"
        f"你是「AI Project Reviewer」的项目复盘分析引擎，负责为代码项目生成深度、诚实、结构化的复盘报告章节。\n"
        f"{lang}\n"
        f"总体原则：结论必须有材料依据；区分「证据支持的结论」与「推测」；"
        f"对代码质量给出真实评价，不奉承、不夸大。"
    )


def _user(title: str, materials: list[tuple[str, str]], body: str) -> str:
    parts = [f"本章节标题：{title}"]
    for name, content in materials:
        if content:
            parts.append(f"【{name}】\n{content}")
    parts.append(body)
    parts.append(_TAIL.format(title=title))
    return "\n\n".join(parts)


def build_section_messages(idx: int, digest_full: str, digest_short: str,
                           evidence_text: str, profile_text: str, quiz_text: str,
                           language: str) -> list[ChatMessage]:
    title = SECTION_TITLES[idx - 1]
    system = _system(language, f"section-{idx}")
    if idx == 4:
        mats = [("项目画像（含关键文件摘录）", digest_full)]
        body = _BODY_4
    elif idx == 5:
        mats = [("项目画像", digest_short), ("AI 生成证据", evidence_text)]
        body = _BODY_5
    elif idx == 6:
        mats = [("项目画像", digest_short), ("个人技能档案", profile_text),
                ("实践验证结果", quiz_text)]
        body = _BODY_6
    elif idx == 7:
        mats = [("项目画像", digest_full)]
        body = _BODY_7
    elif idx == 8:
        mats = [("项目画像", digest_short)]
        body = _BODY_8
    else:
        mats = [("项目画像", digest_full)]
        body = _BODIES.get(idx, "")
    return [ChatMessage(role="system", content=system),
            ChatMessage(role="user", content=_user(title, mats, body))]
